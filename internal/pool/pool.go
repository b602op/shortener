// Package pool предоставляет generic-контейнер Pool для повторного
// использования объектов, поддерживающих метод Reset().
//
// Pool — потокобезопасный и построен поверх sync.Pool: объекты берутся
// из пула через Get и возвращаются через Put, при этом перед возвратом
// объект сбрасывается к нулевому состоянию вызовом Reset(). Это позволяет
// переиспользовать уже выделенные объекты вместо создания новых,
// снижая нагрузку на сборщик мусора.
//
// Типичный сценарий использования — пулинг короткоживущих рабочих
// структур, создаваемых на каждый запрос:
//
//	type Task struct {
//	    UserID   string
//	    ShortURL string
//	}
//
//	func (t *Task) Reset() {
//	    if t == nil {
//	        return
//	    }
//	    t.UserID = ""
//	    t.ShortURL = ""
//	}
//
//	p := pool.New(func() *Task { return &Task{} })
//
//	task := p.Get()      // взять объект из пула (или создать новый)
//	task.UserID = "u-1"  // использовать
//	p.Put(task)          // вернуть: Reset() вызовется автоматически
//
// Пул не гарантирует сохранение объектов: sync.Pool имеет право
// очищать их в любой момент (например, при GC), поэтому Get может
// вернуть новый объект даже после Put.
//
// Объект, возвращённый в пул, больше не должен использоваться
// вызывающим кодом — это стандартное требование sync.Pool.
package pool

import "sync"

// Resetable — интерфейс, которому должны удовлетворять типы,
// хранимые в Pool. Метод Reset сбрасывает состояние объекта к нулевым
// значениям, подготавливая его к безопасному повторному использованию.
//
// Реализация Reset обязана корректно обрабатывать nil-получателя:
// вызов Reset на nil не должен паниковать.
type Resetable interface {
	Reset()
}

// Pool — потокобезопасный контейнер для повторного использования
// объектов типа T. Перед возвратом объекта в пул вызывается Reset().
//
// Нулевое значение Pool не готово к использованию — создавайте пул
// только через New.
type Pool[T Resetable] struct {
	pool sync.Pool
	new  func() T
}

// New создаёт Pool, который использует newFn для создания новых объектов
// при отсутствии свободных в пуле.
//
// Если newFn == nil, Get() возвращает zero value типа T.
func New[T Resetable](newFn func() T) *Pool[T] {
	p := &Pool[T]{new: newFn}
	p.pool.New = func() any {
		if newFn != nil {
			return newFn()
		}
		var zero T
		return zero
	}
	return p
}

// Get возвращает объект из пула. Если пул пуст, создаёт новый через newFn
// (или возвращает zero value, если newFn == nil).
//
// Полученный объект принадлежит вызывающему коду до момента возврата
// в пул через Put.
func (p *Pool[T]) Get() T {
	return p.pool.Get().(T)
}

// Put помещает объект в пул. Перед возвратом вызывает obj.Reset(),
// чтобы подготовить объект к повторному использованию.
//
// После Put объект больше не должен использоваться вызывающим кодом.
func (p *Pool[T]) Put(obj T) {
	obj.Reset()
	p.pool.Put(obj)
}
